import type { Station } from "@/features/stations/stationTypes";

type PresetStationInput = {
  changeuuid: string;
  stationuuid: string;
  name: string;
  url: string;
  urlResolved?: string;
  homepage?: string;
  favicon?: string;
  tags?: string;
  country?: string;
  countrycode?: string;
  state?: string;
  language?: string;
  languagecodes?: string | null;
  votes?: number;
  codec?: string;
  bitrate?: number;
  hls?: number;
  lastcheckok?: number;
  clickcount?: number;
  clicktrend?: number;
};

function presetStation(input: PresetStationInput): Station {
  return {
    changeuuid: input.changeuuid,
    stationuuid: input.stationuuid,
    id: input.stationuuid,
    name: input.name,
    url: input.url,
    urlResolved: input.urlResolved ?? input.url,
    homepage: input.homepage ?? "",
    favicon: input.favicon ?? "",
    tags: input.tags ?? "",
    country: input.country ?? "China",
    countrycode: input.countrycode ?? "CN",
    state: input.state ?? "",
    language: input.language ?? "chinese",
    languagecodes: input.languagecodes ?? "zh",
    votes: input.votes ?? 0,
    codec: input.codec ?? "STREAM",
    bitrate: input.bitrate ?? 0,
    hls: input.hls ?? 0,
    lastcheckok: input.lastcheckok ?? 1,
    clickcount: input.clickcount ?? 0,
    clicktrend: input.clicktrend ?? 0,
  };
}

